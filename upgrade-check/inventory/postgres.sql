-- Row counts of the main tables, soft-deleted rows counted separately where
-- the table has a deletedAt column. Counts only.
select 'migrations_applied', count(*) from migrations;
select 'last_migration', max(name) from migrations;
select 'patients', count(*) from patient;
select 'patients_soft_deleted', count(*) from patient where "deletedAt" is not null;
select 'patients_archived', count(*) from patient where deleted;
select 'patients_id_max', max(id) from patient;
select 'assessments', count(*) from assessment;
select 'assessments_soft_deleted', count(*) from assessment where "deletedAt" is not null;
select 'assessments_archived', count(*) from assessment where deleted;
select 'assessments_id_max', max(id) from assessment;
select 'assessments_by_status ' || status, count(*) from assessment group by status order by 1;
select 'assessments_by_informant ' || coalesce("informantType", 'NULL'), count(*) from assessment group by 1 order by 1;
select 'assessments_with_email_status ' || coalesce("emailStatus", 'NULL'), count(*) from assessment group by 1 order by 1;
select 'assessments_with_submission_date', count(*) from assessment where "submissionDate" is not null;
select 'assessments_with_delivery_date', count(*) from assessment where "deliveryDate" is not null;
select 'assessments_with_expiration_date', count(*) from assessment where "expirationDate" is not null;
select 'users', count(*) from "user";
select 'users_inactive', count(*) from "user" where not active;
select 'users_without_department', count(*) from "user" u where not exists (select 1 from user_department d where d."userId" = u.id);
select 'users_with_several_departments', count(*) from (select "userId" from user_department group by 1 having count(*) > 1) s;
select 'users_with_several_roles', count(*) from (select "userId" from user_role group by 1 having count(*) > 1) s;
select 'users_with_direct_permissions', count(distinct "userId") from user_permission;
select 'roles', count(*) from role;
select 'roles_with_view_all_patients', count(*) from role_permission rp join permission p on p.id = rp."permissionId" where p.name = 'view all patients';
select 'departments', count(*) from department;
select 'departments_inactive', count(*) from department where not active;
select 'patients_in_several_departments', count(*) from (select "patientId" from patient_department group by 1 having count(*) > 1) s;
select 'patients_without_department', count(*) from patient p where not exists (select 1 from patient_department d where d."patientId" = p.id);
select 'caregivers', count(*) from caregiver;
select 'patient_caregiver_links', count(*) from patient_caregiver;
select 'emergency_contacts', count(*) from emergency_contact;
select 'informants', count(*) from informant;
select 'case_manager_links', count(*) from patient_case_manager;
select 'patient_statuses', count(*) from patient_status;
select 'assessment_types', count(*) from assessment_type;
select 'mail_templates', count(*) from mail_template;
select 'disclaimers', count(*) from disclaimer;
select 'reports', count(*) from report;
select 'questionnaire_scripts', count(*) from questionnaire_script;
select 'settings_rows', count(*) from setting;
select 'access_tokens', count(*) from access_token;
select 'access_tokens_not_revoked', count(*) from access_token where not "isRevoked";
